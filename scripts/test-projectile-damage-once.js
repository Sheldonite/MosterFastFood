const assert = require("node:assert/strict");
const { createGame } = require("./game-test-harness");
const game = createGame();
game.run('startSinglePlayer(); closeClassMenu(); player.invulnerableTimer=0; const testBolt={id:"bolt-1"};');
assert.equal(game.run('markProjectileHitPlayer(testBolt,"p1","test")'),true);
assert.equal(game.run('markProjectileHitPlayer(testBolt,"p1","test")'),false);
assert.equal(game.run('markProjectileHitPlayer(testBolt,"p2","test")'),true);
const hp=game.run('player.hp');
assert.equal(game.run('damagePlayer(12,"test",{fixed:true,projectileId:"synced-1",ignoreOverlapGrace:true})'),true);
assert.equal(game.run('damagePlayer(12,"test",{fixed:true,projectileId:"synced-1",ignoreOverlapGrace:true})'),false);
assert.equal(game.run('player.hp'),hp-12);
game.run('const projectile={id:"bolt-2"};');
assert.equal(game.run('damagePlayerFromProjectile(projectile,10,"test",{fixed:true,ignoreOverlapGrace:true})'),true);
assert.equal(game.run('damagePlayerFromProjectile(projectile,10,"test",{fixed:true,ignoreOverlapGrace:true})'),false);
assert.equal(game.run('player.hp'),hp-22);
console.log("Actual client projectile damage once regression passed.");
